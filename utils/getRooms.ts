export const getFeaturedRooms = () => {
    const roomWithAll = rooms
        .filter(room => room.featured === true)
        .map(room => ({
            ...room,
            services: getRoomServices(room.id),
            images: base64Image.filter(image => image.roomId === room.id)
        }));
    return roomWithAll;
}


